export const ASSISTANT_ROLES: AssistantRole[] = [
  {
    id: "tehnadzor",
    label: "Проверка как технадзор",
    hint: "Строгая проверка актов глазами технадзора: замечания по пунктам акта, подписантам, документам качества, датам; однозначные правки — предложениями",
    build: ({ act, acts }) => {
      const list = act ? [act] : acts;
      const which = act
        ? `акт ${act}`
        : list.length > 15
          ? `акты книги (первые 15 из ${list.length}: ${list.slice(0, 15).join(", ")})`
          : `все акты книги: ${list.join(", ")}`;
      return {
        display: `Проверка как технадзор: ${act ? `акт ${act}` : `все акты (${list.length})`}`,
        text: [...TEHNADZOR, `Проверь ${which}.`].join("\n"),
      };
    },
  },
  {
    id: "rd-drafts",
    label: "Черновики актов из РД",
    hint: "Приложите РД (PDF, Word или Excel) — помощник предложит шифр, акты скрытых работ по видам работ, нормативы, п.7 и материалы из спецификации",
    needsRd: true,
    build: ({ rd }) => {
      const text = rd?.text ?? "";
      const cut = text.length > RD_LIMIT;
      return {
        display: `Черновики актов из РД: ${rd?.name ?? "файл"}`,
        text: [
          ...DRAFTS,
          `Текст РД «${rd?.name ?? ""}»${rd?.pages ? ` (страниц: ${rd.pages})` : ""}${cut ? `, первые ${RD_LIMIT} знаков` : ""}:`,
          "<<<",
          cut ? text.slice(0, RD_LIMIT) : text,
          ">>>",
        ].join("\n"),
      };
    },
  },
];
