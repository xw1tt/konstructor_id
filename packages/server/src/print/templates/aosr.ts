import type { AosrData } from "../data.ts";
import { e, field, page, signBlocks } from "./common.ts";
import { withNo } from "@idk/shared/acts/format";

export const CAP_ORG =
  "(фамилия, имя, отчество (последнее - при наличии), адрес места жительства, ОГРНИП, ИНН индивидуального предпринимателя, полное и (или) сокращенное наименование, ОГРН, ИНН, адрес юридического лица в пределах его места нахождения, телефон или факс, полное и (или) сокращенное наименование, ОГРН, ИНН саморегулируемой организации, членом которой является указанное юридическое лицо или индивидуальный предприниматель (за исключением случаев, когда членство в саморегулируемых организациях в области строительства, реконструкции, капитального ремонта объектов капитального строительства не требуется))";
export const CAP_REP =
  "(должность (при наличии), фамилия, инициалы, идентификационный номер в национальном реестре специалистов в области строительства (в случаях, когда это требуется), реквизиты распорядительного документа, подтверждающего полномочия, с указанием полного и (или) сокращенного наименования, ОГРН, ИНН, адреса юридического лица в пределах его места нахождения)";

/** Подписи-пояснения полей АОСР (общие для PDF и Excel). */
export const AOSR_CAPS = {
  object:
    "(наименование объекта капитального строительства в соответствии с проектной документацией, почтовый или строительный адрес объекта капитального строительства)",
  number:
    "(номер акта)",
  date:
    "(дата составления акта)",
  performer:
    "(полное и (или) сокращенное наименование или фамилия, имя, отчество (последнее - при наличии) лица, выполнившего работы, подлежащие освидетельствованию)",
  works:
    "(наименование скрытых работ)",
  p2:
    "(номер, другие реквизиты чертежа, наименование проектной и (или) рабочей документации, сведения о лицах, осуществляющих подготовку раздела проектной и (или) рабочей документации)",
  p3:
    "(наименования строительных материалов (изделий), реквизиты сертификатов и (или) других документов, подтверждающих их качество и безопасность, в случае если необходимо указывать более 5 документов, указывается ссылка на их реестр, который является неотъемлемой частью акта)",
  p4:
    "(исполнительные схемы и чертежи, результаты экспертиз, обследований, лабораторных и иных испытаний выполненных работ, проведенных в процессе строительного контроля)",
  normative:
    "(наименования и структурные единицы технических регламентов, иных нормативных правовых актов, разделы проектной и (или) рабочей документации)",
  nextWorks:
    "(наименования работ, строительных конструкций, участков сетей инженерно-технического обеспечения)",
  attachments:
    "(исполнительные схемы и чертежи, результаты экспертиз, обследований, лабораторных и иных испытаний)",
};

export function aosrHtml(d: AosrData): string {
  const head = `
    <div class="block"><p>Объект капитального строительства:</p>${field(d.objectName,
      AOSR_CAPS.object)}</div>
    <div class="block"><p>Застройщик, технический заказчик, лицо, ответственное за эксплуатацию здания, сооружения, или региональный оператор:</p>${field(d.developer, CAP_ORG)}</div>
    <div class="block"><p>Лицо, осуществляющее строительство, реконструкцию, капитальный ремонт:</p>${field(d.builder, CAP_ORG)}</div>
    <div class="block"><p>Лицо, осуществляющее подготовку проектной документации:</p>${field(d.designer, CAP_ORG)}</div>
    <div class="title">АКТ</div>
    <div class="subtitle">освидетельствования скрытых работ</div>
    <div class="numdate"><div>${field(d.number ? `${withNo(String(d.number ?? ""))}` : "", AOSR_CAPS.number)}</div><div>${field(d.date, AOSR_CAPS.date)}</div></div>`;
  const reps = d.reps.map((r) => `<div class="block"><p>${e(r.label)}:</p>${field(r.lines, CAP_REP)}</div>`).join("");
  const body = `
    <div class="block"><p>произвели осмотр работ, выполненных:</p>${field(d.performerOrg,
      AOSR_CAPS.performer)}</div>
    <p>и составили настоящий акт о нижеследующем:</p>
    <div class="block p1"><p>1. К освидетельствованию предъявлены следующие работы:</p>${field(d.works, AOSR_CAPS.works)}</div>
    <div class="block"><p>2. Работы выполнены по проектной документации:</p>${field(d.p2,
      AOSR_CAPS.p2)}</div>
    <div class="block"><p>3. При выполнении работ применены:</p>${field(d.p3,
      AOSR_CAPS.p3)}</div>
    <div class="block"><p>4. Предъявлены документы, подтверждающие соответствие работ предъявляемым к ним требованиям:</p>${field(d.p4,
      AOSR_CAPS.p4)}</div>
    <div class="block"><p>5. Даты:</p><div class="dates"><span>начала работ</span>${field(d.dateStart)}<span>окончания работ</span>${field(d.dateEnd)}</div></div>
    <div class="block"><p>6. Работы выполнены в соответствии с</p>${field(d.normative,
      AOSR_CAPS.normative)}</div>
    <div class="block"><p>7. Разрешается производство последующих работ:</p>${field(d.nextWorks,
      AOSR_CAPS.nextWorks)}</div>
    <div class="block inline"><span>Дополнительные сведения:</span>${field(d.extraInfo)}</div>
    <div class="block inline"><span>Акт составлен в</span>${field(String(d.copies))}<span>экземплярах (в случае заполнения акта на бумажном носителе).</span></div>
    <div class="block"><p>Приложения:</p>${field(d.attachments,
      AOSR_CAPS.attachments)}</div>
    ${signBlocks(d.signs)}`;
  return page(d.number, head + reps + body, "aosr");
}
