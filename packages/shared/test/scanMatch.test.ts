import { test } from "node:test";
import assert from "node:assert/strict";
import { matchMaterials, flat, fixOcrDates } from "@idk/shared/scan/match";

const MATS = [
  { name: "Кабель силовой ВВГнг(А)-LS 3х2,5", mark: "ВВГнг(А)-LS 3х2,5-0,66", manufacturer: 'ООО "Кабельный завод"' },
  { name: "Кабель силовой ВВГнг(А)-LS 5х4", mark: "ВВГнг(А)-LS 5х4-0,66" },
  { name: "Труба гофрированная ПНД 20 с зондом", article: "71920" },
  { name: "Кабель для промышленного интерфейса RS-485 СегментКИ-485" },
  { name: "Шайба с узкими полями М8" },
];

test("похожие буквы и знаки: OCR «BBГнг(A)-LS 3x2.5» = «ВВГнг(А)-LS 3х2,5»", () => {
  assert.equal(flat("BBГнг(A)-LS 3x2.5"), flat("ВВГнг(А)-LS 3х2,5"));
});

test("сертификат на серию ВВГнг(А)-LS — оба сечения; точная марка — выше; посторонние — нет", () => {
  const h = matchMaterials("СЕРТИФИКАТ СООТВЕТСТВИЯ Продукция: кабели силовые марки BBГнг(A)-LS 3x2,5-0,66, 5х4 изготовитель ООО Кабельный завод", MATS);
  assert.deepEqual(h.map((x) => x.name).slice(0, 2), ["Кабель силовой ВВГнг(А)-LS 3х2,5", "Кабель силовой ВВГнг(А)-LS 5х4"]);
  assert.ok(h[0].score > h[1].score);
  assert.ok(!h.some((x) => /Шайба|Труба/.test(x.name)));
});

test("паспорт трубы по артикулу; кабель RS-485 по словам наименования", () => {
  assert.equal(matchMaterials("ПАСПОРТ Труба ПНД гофр. арт. 71920 d20", MATS)[0].name, "Труба гофрированная ПНД 20 с зондом");
  assert.equal(matchMaterials("Кабели для промышленного интерфейса RS-485 марки СегментКИ-485", MATS)[0].name, "Кабель для промышленного интерфейса RS-485 СегментКИ-485");
});

test("даты после OCR: «1О.О6.2О26», «З1 . 12 . 2025»", () => {
  assert.equal(fixOcrDates("по 1О.О6.2О26 включительно"), "по 10.06.2026 включительно");
  assert.equal(fixOcrDates("от З1 . 12 . 2025 г."), "от 31.12.2025 г.");
  assert.equal(fixOcrDates("ГОСТ 31996-2012"), "ГОСТ 31996-2012");
});
