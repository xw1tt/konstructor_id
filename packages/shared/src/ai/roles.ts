// 0.34: роли помощника — готовые задачи, которые больше, чем «найди и исправь». Кнопка роли отправляет модели
// подробное задание (в чате видна короткая подпись). Изменения книги — как всегда, только предложениями.
export interface RoleInput {
  /** Акт под курсором или выбранный. */
  act: string | null;
  /** Все акты книги. */
  acts: string[];
  /** Текст приложенной рабочей документации (для черновиков). */
  rd?: { name: string; text: string; pages?: number } | null;
}
export interface AssistantRole {
  id: string;
  label: string;
  /** Подсказка на кнопке. */
  hint: string;
  /** Нужен файл РД. */
  needsRd?: boolean;
  /** Подпись в чате и полное задание модели. */
  build(i: RoleInput): { display: string; text: string };
}

